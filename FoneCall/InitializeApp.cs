        public static void SaveOptsToDB()
        {
            #region workflow
            // based on Copilot suggestion; worked (sort of) only or Arguments
            // nonworking commented out
            // the help.txt file is generated by running scrcpy.exe with the --help option
            // and pasting the output to a text file; everything but Argumennts were
            // transferred to an Excel csv and imported manually after this completed
            //
            // switched to parameterized DBB INSERT removed need to escape SQLLte
            // special characters
            #endregion

            int hderLine = -1;
            string fqnHelp = @"E:\FoneCall\Data\scrcpy help.txt",
                   role = "", optTxt = "", explain = "";

            // Guard: if help file is missing or empty, do nothing and do not throw
            try
            {
                if (!File.Exists(fqnHelp))
                {
                    LogR.Norm($"SaveOptsToDB: help file not found: {fqnHelp}");
                    return;
                }

                string[] opt = File.ReadAllLines(fqnHelp);
                if (opt == null || opt.Length == 0)
                {
                    LogR.Norm($"SaveOptsToDB: help file empty: {fqnHelp}");
                    return;
                }

                var lines = opt.Where(s => !string.IsNullOrWhiteSpace(s)).ToArray();
                var sb = new StringBuilder();
                for (int i = 0; i < lines.Length; i++)
                {
                    var line = lines[i];
                    if (string.IsNullOrEmpty(line)) continue;

                    if (line.StartsWith("Options"))
                    {
                        role = "ARG";
                        optTxt = "Options:/Arguments";
                        explain = $"Options impacting scrcpy execution during initialization and after phone is mirrored on the computer screen.\n" +
                                  $"data source: Help for scrcpy 4.1 on {DateTime.Now: yyyy MMM dd}";
                        save2db(role, optTxt, explain);
                        hderLine = -1;
                        sb.Clear();
                    }
                    else if (line.StartsWith("    -"))
                    {
                        // header for an option within current role
                        optTxt = line.Trim();
                        hderLine = i;
                        sb.Clear();

                        // collect following lines until next header or top-level section
                        int j = i + 1;
                        while (j < lines.Length && !lines[j].StartsWith("    -"))
                        {
                            sb.Append((sb.Length == 0) ? lines[j].Trim() : "\n" + lines[j].Trim());
                            j++;
                        }

                        save2db(role, optTxt, sb.ToString());
                        i = j - 1; // skip processed lines
                    }
                }
            }
            catch (Exception ex)
            {
                // log and swallow so tests that expect no-throw on missing/empty file behave correctly
                LogR.Norm($"SaveOptsToDB exception: {ex}");
            }

            void save2db(string r, string o, string e)
            {
                Args args = new Args { Role = r, Arg = o, Explain = e };
                DBC.SaveArgs_Model(args);
            }
        }
        public static void SaveRTFtoDB()
        {
            #region rtf code behind acquisition
            // 2 RTF editors used Microsoft Word and Jarte Plus
            // Word for doc dev and Jarte for "code behind"
            // Word''s  "code behind" was too complex to manipulate
            // programmatically and Jarte too limited for creation
            // process was [1] create .docx in Word [2] Save As .rtf  [3] close doc
            // [4] open in Jarte [5] Save As working name referenced in ReadAllText
            #endregion
            string rtfCode = File.ReadAllText( @"E:\__DOCS\FoneCallWelcome.rtf" );
            // removes non-printable NUL appended to Jarte RTF files
            rtfCode = Regex.Replace( rtfCode, @"\p{C}+", string.Empty );
            rtfCode = rtfCode.Replace( "'", "''" ); // SQLite single quote escape
            DBC.DeleteKVPrecord( KVP_Keys.Intro );
            DBC.SaveKVP( KVP_Keys.Intro, rtfCode );
            LogR.Norm( "RTF saved to DB" );
        }
        private static async Task RunChecks( bool startHeader )
        {
            string msg = "";

            try
            {
                #region Perform Startup checks
                if (Directory.Exists( Paths.AppData ))
                {
                    bool dbOK = await DBC.CheckDB();
                    _logMsgs.AppendLine( $"DB integrity OK = {dbOK}" );
                    if (!dbOK) callMsgBx( noLog: false, noDataDir: false, notCatch: true, ex: null );
                }
                else callMsgBx( noLog: false, noDataDir: true, notCatch: true, ex: null );
                #endregion
            }
            catch (Exception ex)
            {
                callMsgBx( noLog: false, noDataDir: false, notCatch: false, ex );
            }

            LogSizeCheck();

            void callMsgBx( bool noLog, bool noDataDir, bool notCatch, Exception ex )
            {
                #region MSGBOX PARAMETERS
                _cmb.I_MsgType = States.Fail;
                _cmb.I_Msg = msg;
                _cmb.I_Txt_Btn1 = noLog ? "New Log" : notCatch ? "Exit" : "OK";
                #endregion
                string mbReturn = WinCtrl.CstmmMB_Call( _cmb );
                LogR.Norm( $"Warning option selected: {mbReturn}" );
            }
        }
        private static void LogSizeCheck()
        {
            int appStarts = 0;
            string sessHdr = "===== Starting FoneCall",
                   logPath = Paths.AppLog;

            if (File.Exists( logPath ))
            {
                string[] logLines = File.ReadAllLines( logPath );
                if (new FileInfo( logPath ).Length > 1000000) //0.001 GB/1 MB; approx 28000 lines
                {
                    int headerLine = 0;
                    StringBuilder nuLog = new StringBuilder();
                    nuLog.AppendLine( "!!!!! LOG HAS BEEN TRIMMED !!!!!" );
                    for (int i = 0; i < logLines.Length; i++)
                    {
                        if (logLines[i].Contains( sessHdr )) headerLine++;
                        if (headerLine >= 20) nuLog.AppendLine( logLines[i] );
                    }
                    int retries = 0, maxRetries = 10;
                    while (retries < maxRetries)
                    {
                        try
                        {
                            File.Delete( logPath );
                            File.WriteAllText( logPath, nuLog.ToString() );
                            retries = maxRetries;
                            logLines = File.ReadAllLines( logPath );
                        }
                        catch (Exception)
                        {
                            retries++;
                            Thread.Sleep( 150 );
                        }
                    }
                }
                else
                {
                    for (int i = 0; i < logLines.Length; i++)
                        if (logLines[i].Contains( sessHdr )) appStarts++;
                }
                _logMsgs.AppendLine( $"\ttrimmed log in bytes: {new FileInfo( logPath ).Length}" +
                              $" || lines: {logLines.Length}" +
                              $" || starts in log: {appStarts}" );
            }
        }
